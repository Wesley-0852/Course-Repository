#Comparrison operators are what you use to create conditions - they produce boolians (bool's)
#EXAMPLE:

a = 10
b = 3

print(a == b)  #This "==" means equal to
print(a != b)  #This "!=" means NOT equal to
print(a > b)   # This ">" means greater than
print(a < b)   # This "<" means less than
print (a >= b) # This ">=" means Greater than or Equal to
print (a <= b) # This "<=" means Less than or Equal to